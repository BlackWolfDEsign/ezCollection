-- Emote-Makros. {e:TOKEN} wird beim Übernehmen durch den Emote-Befehl der Client-Sprache
-- ersetzt (z. B. /danke auf deDE, /thank auf enUS). Emotes ohne Namen wirken auf dein Ziel.
-- Ausnahme Spucken: WoW Forever nimmt dort kein Ziel mehr an; {e:SPIT} wird „/ezmacro emote SPIT“ (Emote.lua).
-- Ausnahme Angriff: mit angreifbarem Ziel führt ezMacro Blizzards Emote ATTACKMYTARGET aus (nennt das Ziel), sonst
-- CHARGE; {e:CHARGE} wird darum „/ezmacro emote CHARGE“ – die Wahl fällt beim Klick (Emote.lua, TARGET_EMOTE).
-- Sätze ({t:...}) gehen in Sagen (/s) oder Gruppe (/p) – nur per Tastendruck, nie automatisch.
-- Herkunft (MACRO-28, Beleg: docs/roadmap/ezMacro.md, „Herkunft der Bestandsvorlagen“): eigene Texte in eigener Form,
-- nichts aus fremden Addons. Die Emote-Token (THANK, SPIT …) sind Blizzards eigene Namen aus dem Client
-- (EMOTE<n>_TOKEN); die Befehle dazu liest ezCore zur Laufzeit aus dem Client, die Sätze stehen in Locale.lua.

