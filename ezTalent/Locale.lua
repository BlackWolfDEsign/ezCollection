-- Blizzards Knopf mit seinem echten Namen (docs/roadmap/ezTalent.md, „Blizzards Knopf … nennen“)
---------------------------------------------------------------------------
-- ezTalents eigener Knopf heißt „Übernehmen“ – wie Blizzards Knopf unten im Talent- und im Vermächtnis-Fenster, der
-- die vorgemerkten Punkte gültig macht. Damit die Texte den meinen, den der Spieler sieht, steht dort der Name aus
-- dem Client: beide Fenster beschriften ihren ApplyButton mit der globalen Zeichenkette TALENT_FRAME_APPLY_BUTTON_TEXT
-- (Forever-Quelle, Zweig forever: Blizzard_PlayerSpells/Camelot/ClassTalents/Blizzard_ClassTalentsFrame.xml und
-- Blizzard_LegacySystem/Blizzard_LegacyTree.xml, je text="TALENT_FRAME_APPLY_BUTTON_TEXT"). In den Texten oben steht
-- dafür die Marke {apply}; sie wird hier einmal beim Laden ersetzt (globale Zeichenketten stehen vor jedem Addon
-- bereit). Liefert der Client nichts Brauchbares, gilt der Rückfall BLIZZARD_APPLY der jeweiligen Sprache.
ns.BLIZZARD_APPLY_MARK = "{apply}"

-- → Name von Blizzards Knopf aus dem Client, sonst fallback. Nur gelesen (rawget), nie geschrieben.
function ns.BlizzardApplyName(fallback)
    local name = rawget(_G, "TALENT_FRAME_APPLY_BUTTON_TEXT")
    if type(ezCore.IsSecret) == "function" and ezCore.IsSecret(name) then return fallback end
    if type(name) ~= "string" then return fallback end
    name = ezCore.Trim(name)   -- Core.Trim (Gesamtreview 18.11.2026, T16-15)
    if name == "" then return fallback end
    return name
end

-- Ersetzt die Marke in allen Texten einer Sprache. Texte mit Platzhaltern (%s, %d) laufen später durch string.format:
-- ein „%“ im Namen wird dort verdoppelt, sonst bliebe es wörtlich stehen. → Zahl der geänderten Texte
function ns.FillBlizzardNames(texts, apply)
    local changed = 0
    if type(texts) ~= "table" or type(apply) ~= "string" then return changed end
    for key, text in pairs(texts) do
        if type(text) == "string" and text:find(ns.BLIZZARD_APPLY_MARK, 1, true) then
            local name = apply
            if text:find("%%[%d%.%-]*[sdfi]") then name = apply:gsub("%%", "%%%%") end
            texts[key] = text:gsub(ns.BLIZZARD_APPLY_MARK, function() return name end)
            changed = changed + 1
        end
    end
    return changed
end

ns.FillBlizzardNames(de, ns.BlizzardApplyName(de.BLIZZARD_APPLY))
ns.FillBlizzardNames(en, ns.BlizzardApplyName(en.BLIZZARD_APPLY))

ns.L = ezCore.NewLocale(de, en, ezCore.L)
